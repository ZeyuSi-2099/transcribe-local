"""P3 融合报告「用哪门语言写」的唯一指令来源，以及〈依据〉列的机读标签。

规则（Duner 2026-08-30 定）：**我们写的字跟界面语言走，录音里的内容原样不翻。**
落到 P3 报告上，同一份文件里有三种东西，语言各不相同：

  · **骨架**（章节标题 / 表头 / `无` / 围栏）→ 一律**中文原样**。它不是给人看的文字，
    是 `review.py` 的解析契约；报告本身用户看不到（只留档 30 天供我们诊断）。
  · **依据 / 原因 / 结果** 三列的说明 → **界面语言**。这是用户在复核卡上真正读到的字。
  · **时间码 / 候选 / 终稿写法 / 搜索词 / 引文** → 录音语种，原样不翻。

⚠️ **「让它用某门语言写报告」这件事不能只说一句**（2026-08-29 实测，生产同款 DeepSeek Flash
   + 真实西语生产稿）：只说「用西语写」，它把**章节标题和表头一起翻了**——
   `## 实体定字（硬证据）` → `## Fijación de entidades`。日语那轮更阴：写成 `## 実体定字`，
   与 `实体定字` 肉眼几乎一样，只差一个汉字字形。两轮拿 `review._section_rows` 一解析，
   **实体 0 行、联网 0 行、存疑 0 行**——终稿照常交付、照常计费，用户只是一张卡片都没有，
   而且哪儿都不报错。所以骨架必须逐条点名、并且写明「照抄，别凭印象重打」。

⚠️ **依据列还兼着一件机读的活**（`review._basis` → 卡片上那枚证据标签）：它靠在中文里搜
   「联网 / 术语库 / 声学 / 多数」这几个词判定。15 单生产留档 119 行实测，**97 行（81%）
   靠这几个中文词拿到了非兜底的标签**——依据一改成日语，这 97 行会**全部**掉回中性的
   「引擎证据」。所以依据列另要求带一个 ASCII 标签，`review.py` 认标签、显示时剥掉。
   **机读的东西不该跟给人看的文案是同一串字**（同 `pp_lang.FIX_COUNT_MARK` 的教训）。
"""
from __future__ import annotations

import re

from .ui_lang import norm, ui_lang_name  # noqa: F401  (norm 供调用方规范化)

# ── 〈依据〉列的机读标签 ──────────────────────────────────────────────
#
# 四档，与 `review._basis` 现有的四个返回值一一对得上。**只让模型填一个**：
# 让它填多个的话「术语库命中且多数正确」这类会填出两三个，而我们只需要主证据。
BASIS_TAGS = ("web", "term", "majority", "other")

# 行首标签。`review._cell` 只在「整格就是一个时间码」时剥方括号，所以这里要自己剥。
BASIS_TAG_RE = re.compile(r"^\s*\[(" + "|".join(BASIS_TAGS) + r")\]\s*")


def split_basis_tag(cell: str) -> tuple[str, str]:
    """`[majority] 三轨一致` → `("majority", "三轨一致")`；没有标签 → `("", 原文)`。"""
    m = BASIS_TAG_RE.match(cell or "")
    return (m.group(1), cell[m.end():].strip()) if m else ("", (cell or "").strip())


# ── 骨架：必须被原样照抄的那些串 ──────────────────────────────────────
#
# **单独列成数据、由 directive() 渲染进去**，不是直接写在那段大文本里（2026-08-30 订正）：
# 守卫要问的是「review 真正在解析的每一个章节名，是不是都在**照抄清单**里」。
# 写在大文本里的话，`实体定字` 在后面「〈实体定字〉表的依据列」那句里也出现，
# 于是把整块照抄清单删掉，按字符串搜的守卫照样绿——**造回 bug 验过，真绿了**。
SKELETON = (
    "## 实体定字（硬证据）",
    "## 联网核实",
    "## 存疑 [❓]",
    "## 上游风险",
    "## 出稿前复查",
    "## 润色",
    "| 时间码 | 各轨候选 | 终稿 | 依据 |",
    "| # | 搜索词 | 为定哪个词（时间码） | 结果 | 建议入库? |",
    "| 时间码 | 终稿写法 | 原因 |",
    "===DOUBT===",
    "无",
)


def _skeleton_bullets() -> str:
    return "\n".join(f"- `{x}`" for x in SKELETON)


def directive(ui_lang: str | None) -> str:
    """拼一段语言指令，追加在 SKILL.md 之后（所以它覆盖 skill 里的默认写法）。

    **八门都发，中文也发**——中文那份除了语言名是「简体中文」之外一字不差，于是
    「加了指令」这条路每一单都在跑，不会出现「只有外语用户才走的分支平时没人测」。
    """
    name = ui_lang_name(ui_lang)
    return f"""

---

## 本次任务的语言（覆盖上面〈输出〉节里任何与语言有关的默认写法）

报告里有三种东西，**语言不一样，别混**。

### 一、骨架 —— 原样照抄下面这些中文，一个字都不许改、不许翻译

这些不是给人读的文字，是**程序要读的标记**。翻掉了复核清单一条卡都出不来，
而且**不报任何错**（终稿照常交付，用户只是永远看不到卡片）：

{_skeleton_bullets()}

⛔ 特别注意：**日文汉字与简体汉字不是同一个字**（`実体定字` ≠ `实体定字`，只差一个字形）。
   请**照抄**上面的字符串，不要凭记忆重打。

### 二、你写给用户看的说明 —— 一律用 {name} 书写

只有这几处是自然语言说明，全部用 {name}：

- 〈实体定字〉表的 **依据** 列
- 〈存疑〉表的 **原因** 列
- 〈联网核实〉表的 **结果** 列
- 〈上游风险〉〈出稿前复查〉〈润色〉几节里的说明文字

### 三、这些一律原样保留，**不要翻译**

时间码、各轨候选、终稿写法、引擎代号（ELV / DB / GEM / AAI…）、搜索词、专有名词，
以及任何**从稿子里摘出来的原文片段**——那是录音里的内容，不是我们的话。

### 四、〈依据〉列每一格必须以一个机读标签开头

〈实体定字〉表 **依据** 列的每一格，先照抄下面四个标签之一（含方括号），空一格，再写说明：

- `[web]` —— 主要靠联网核实定的字
- `[term]` —— 主要靠术语库命中定的字
- `[majority]` —— 主要靠各轨多数 / 声学一致定的字
- `[other]` —— 其余（文件名元数据、说话人复述、上下文语义）

**只填一个**，填主要的那条证据；拿不准填 `[other]`。标签是给程序读的，用户看不到它；
后面那句说明才是给人看的，用 {name} 写。
"""


