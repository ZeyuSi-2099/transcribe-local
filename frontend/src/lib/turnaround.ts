// 出稿时长的唯一来源（2026-08-31 生产实测后新增）。
//
// 🔴 **为什么要有这个文件**：这个数字原本是**手打在 63 个地方**的（八门语言 × 首页名片/
// hero 一行/可见 FAQ/结构化 FAQ + 27 门语种页 × 三处 + 应用内一处 + 六本对照本）。
// 上线时写的是「1 小时录音约 10 分钟出稿」，而生产实测 17 个长单里**最快的一单也要 18 分钟**，
// 中位 22 分钟——没有任何一单达到过那个数。流水线这两个月改了很多次（主轨整档直传、
// 参考轨挂进 27 门、P3 换档），改的人是工程师，**没有任何东西会提醒他去翻八门语言的营销文案**。
//
// ⇒ 现在数字从这里注入。改一个常量，八门全站 + 应用内的预计时间一起跟着变。
//
// 📐 **这个数是怎么来的**（生产库 73 单，量具 = `metrics.elapsedSec` 与 `updated_at−created_at`，
// 两者只差 0.4 分钟 ⇒ 慢在流水线本身，不在派单/开机）：
//   录音 ≥25 分钟的单 n=17，出稿÷录音 中位 0.37、区间 0.30–0.62
//   实测：38 分 → 13.8–20.4 分 ｜ 53 分 → 18.5/22.8 分 ｜ 60 分 → 33.4 分 ｜ 87 分 → 26.5 分
//   拟合：出稿 ≈ 5 分钟固定 + 录音 × 0.27
//   ⇒ 1 小时录音 中位 22 分钟，17 单里 15 单 ≤30 分钟（88%）
// 取 30 而不是 22：**这是对外承诺，要留余量**。并发会明显拉长尾巴（实测 8 单同时跑时，
// 3.3 分钟的音频最慢跑到 21 分钟），P3 本身方差也大。
//
// ⚠️ **它同时是应用内「约 X 分钟」的来源**（`flow.etaMinutes`）。分成两份写的后果不是报错，
// 是用户传一单就看见首页说 30、界面说 36 ——我们自己前后矛盾，而两处都"没错"。

/** 1 小时录音，通常多少分钟内出稿。对外文案与应用内预计时间共用这一个数。 */
export const TURNAROUND_MIN_PER_HOUR = 30;

/** 预计出稿时长 ÷ 录音时长。给应用内的「约 X 分钟」用。
 *
 * ⚠️ 它比实测中位（0.37）保守，是**故意的**：先报久、提前完成，方向安全；
 * 反过来（报 22 分钟、实际 30 分钟）每一单都是一次失望。 */
export const TURNAROUND_RATIO = TURNAROUND_MIN_PER_HOUR / 60;
